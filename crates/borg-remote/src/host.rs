async fn probe_provider(
    provider: CodingProvider,
    managed_kimi: bool,
    mode: ProviderProbeMode,
) -> ProviderCapability {
    let (version, subscription_authenticated) = match mode {
        ProviderProbeMode::Detailed => {
            let (version, auth_status) = tokio::join!(
                async {
                    command_output(provider.executable(), &["--version"])
                        .await
                        .ok()
                        .filter(|value| !value.is_empty())
                },
                async {
                    match provider {
                        CodingProvider::Codex
                        | CodingProvider::Claude
                        | CodingProvider::OpenCode => provider_auth_status(provider).await.ok(),
                        CodingProvider::Kimi
                        | CodingProvider::OpenRouter
                        | CodingProvider::OpenAiCompatible => None,
                    }
                }
            );
            let authenticated = match provider {
                CodingProvider::Codex => auth_status
                    .as_deref()
                    .is_some_and(codex_auth_status_authenticated),
                CodingProvider::Claude => auth_status
                    .as_deref()
                    .is_some_and(claude_auth_status_authenticated),
                CodingProvider::OpenCode => auth_status
                    .as_deref()
                    .is_some_and(opencode_auth_status_authenticated),
                CodingProvider::Kimi
                | CodingProvider::OpenRouter
                | CodingProvider::OpenAiCompatible => false,
            };
            (version, authenticated)
        }
        ProviderProbeMode::Admission => {
            let authenticated = provider_subscription_credentials_present(provider);
            #[cfg(target_os = "macos")]
            let authenticated = if provider == CodingProvider::Claude && !authenticated {
                provider_auth_status(provider)
                    .await
                    .ok()
                    .as_deref()
                    .is_some_and(claude_auth_status_authenticated)
            } else {
                authenticated
            };
            (None, authenticated)
        }
    };
    let mut auth_methods = Vec::new();
    let mut detail = Vec::new();
    match provider {
        CodingProvider::Codex => {
            if subscription_authenticated {
                auth_methods.push(ProviderAuthMethod::Subscription);
                detail.push("Codex subscription authenticated");
            }
            if nonempty_env("OPENAI_API_KEY").is_some() {
                auth_methods.push(ProviderAuthMethod::ApiKey);
                detail.push("OpenAI API key configured");
            }
        }
        CodingProvider::Claude => {
            if subscription_authenticated {
                auth_methods.push(ProviderAuthMethod::Subscription);
                detail.push("Claude subscription authenticated");
            }
            if borg_provider::credentials::api_key(
                borg_provider::credentials::ApiKeyCredential::Anthropic,
            )
            .is_some()
            {
                auth_methods.push(ProviderAuthMethod::ApiKey);
                detail.push("Anthropic API key configured");
            }
        }
        CodingProvider::OpenCode => {
            if subscription_authenticated {
                auth_methods.push(ProviderAuthMethod::Subscription);
                detail.push("OpenCode provider credentials available");
            }
        }
        CodingProvider::Kimi => {
            if managed_kimi {
                auth_methods.push(ProviderAuthMethod::Endpoint);
                detail.push("Borg gateway credentials available");
            } else if nonempty_env("BORG_KIMI_API_KEY").is_some()
                || nonempty_env("MOONSHOT_API_KEY").is_some()
            {
                auth_methods.push(ProviderAuthMethod::ApiKey);
                detail.push("Kimi API key configured");
            }
        }
        CodingProvider::OpenRouter => {
            if borg_provider::credentials::api_key(
                borg_provider::credentials::ApiKeyCredential::OpenRouter,
            )
            .is_some()
            {
                auth_methods.push(ProviderAuthMethod::ApiKey);
                detail.push("OpenRouter API key configured");
            }
        }
        CodingProvider::OpenAiCompatible => {
            // The native generic route deliberately has a localhost default,
            // but it is only an advertised lane after the caller configured an
            // endpoint or model (the local-server bootstrap does that before
            // probing). A local endpoint does not require a bearer key.
            let endpoint_configured = nonempty_env("BORG_OPENAI_COMPATIBLE_BASE_URL").is_some()
                || nonempty_env("BORG_OPENAI_COMPATIBLE_MODEL").is_some();
            if endpoint_configured {
                auth_methods.push(ProviderAuthMethod::Endpoint);
                detail.push("OpenAI-compatible endpoint configured");
                if nonempty_env("BORG_OPENAI_COMPATIBLE_API_KEY")
                    .or_else(|| nonempty_env("BORG_OPENAI_API_KEY"))
                    .or_else(|| nonempty_env("OPENAI_API_KEY"))
                    .is_some()
                {
                    auth_methods.push(ProviderAuthMethod::ApiKey);
                    detail.push("endpoint API key configured");
                }
            }
        }
    }
    let authenticated = !auth_methods.is_empty();
    let installed = match provider {
        // These routes execute in Borg's native harness; they do not depend
        // on a separately installed `borg` executable being discoverable in a
        // service user's PATH.
        CodingProvider::Kimi | CodingProvider::OpenRouter | CodingProvider::OpenAiCompatible => {
            true
        }
        CodingProvider::Codex | CodingProvider::Claude | CodingProvider::OpenCode => match mode {
            ProviderProbeMode::Admission => {
                executable_in_path(Path::new(provider.executable())).is_some()
            }
            ProviderProbeMode::Detailed => version.is_some(),
        },
    };
    let can_spawn = installed && authenticated;
    ProviderCapability {
        provider,
        installed,
        version,
        authenticated,
        auth_detail: (!detail.is_empty()).then(|| detail.join("; ")),
        auth_methods,
        can_spawn,
        usage: None,
    }
}

fn provider_subscription_credentials_present(provider: CodingProvider) -> bool {
    match provider {
        CodingProvider::Codex => codex_auth_path()
            .and_then(|path| read_bounded_auth_json(&path))
            .as_ref()
            .is_some_and(codex_auth_json_authenticated),
        CodingProvider::Claude => {
            nonempty_env("CLAUDE_CODE_OAUTH_TOKEN").is_some()
                || claude_credentials_path()
                    .and_then(|path| read_bounded_auth_json(&path))
                    .as_ref()
                    .is_some_and(claude_auth_json_authenticated)
        }
        CodingProvider::OpenCode => opencode_auth_json()
            .as_ref()
            .is_some_and(opencode_auth_json_authenticated),
        CodingProvider::Kimi | CodingProvider::OpenRouter | CodingProvider::OpenAiCompatible => {
            false
        }
    }
}

fn codex_auth_path() -> Option<PathBuf> {
    nonempty_path_env("CODEX_HOME")
        .map(|directory| directory.join("auth.json"))
        .or_else(|| nonempty_path_env("HOME").map(|home| home.join(".codex").join("auth.json")))
}

fn claude_credentials_path() -> Option<PathBuf> {
    nonempty_path_env("CLAUDE_SECURESTORAGE_CONFIG_DIR")
        .or_else(|| nonempty_path_env("CLAUDE_CONFIG_DIR"))
        .map(|directory| directory.join(".credentials.json"))
        .or_else(|| {
            nonempty_path_env("HOME").map(|home| home.join(".claude").join(".credentials.json"))
        })
}

fn opencode_auth_json() -> Option<serde_json::Value> {
    if let Ok(contents) = std::env::var("OPENCODE_AUTH_CONTENT")
        && let Some(value) = parse_bounded_auth_json(contents.as_bytes())
    {
        return Some(value);
    }
    let data_home = nonempty_path_env("XDG_DATA_HOME")
        .or_else(|| nonempty_path_env("HOME").map(|home| home.join(".local").join("share")))?;
    read_bounded_auth_json(&data_home.join("opencode").join("auth.json"))
}

fn nonempty_path_env(name: &str) -> Option<PathBuf> {
    std::env::var_os(name)
        .filter(|value| !value.is_empty())
        .map(PathBuf::from)
}

fn read_bounded_auth_json(path: &Path) -> Option<serde_json::Value> {
    let file = fs::File::open(path).ok()?;
    let mut bytes = Vec::new();
    file.take(PROVIDER_AUTH_JSON_MAX_BYTES + 1)
        .read_to_end(&mut bytes)
        .ok()?;
    parse_bounded_auth_json(&bytes)
}

fn parse_bounded_auth_json(bytes: &[u8]) -> Option<serde_json::Value> {
    if u64::try_from(bytes.len()).ok()? > PROVIDER_AUTH_JSON_MAX_BYTES {
        return None;
    }
    serde_json::from_slice(bytes).ok()
}

fn nonempty_json_string(value: Option<&serde_json::Value>) -> bool {
    value
        .and_then(serde_json::Value::as_str)
        .is_some_and(|value| !value.trim().is_empty())
}

fn codex_auth_json_authenticated(value: &serde_json::Value) -> bool {
    value
        .get("tokens")
        .and_then(serde_json::Value::as_object)
        .is_some_and(|tokens| {
            tokens
                .values()
                .any(|value| nonempty_json_string(Some(value)))
        })
        || nonempty_json_string(value.get("OPENAI_API_KEY"))
}

fn claude_auth_json_authenticated(value: &serde_json::Value) -> bool {
    value
        .get("claudeAiOauth")
        .and_then(serde_json::Value::as_object)
        .is_some_and(|oauth| {
            nonempty_json_string(oauth.get("accessToken"))
                || nonempty_json_string(oauth.get("refreshToken"))
        })
}

fn opencode_auth_json_authenticated(value: &serde_json::Value) -> bool {
    value
        .as_object()
        .is_some_and(|providers| providers.values().any(opencode_auth_entry_authenticated))
}

fn opencode_auth_entry_authenticated(value: &serde_json::Value) -> bool {
    match value.get("type").and_then(serde_json::Value::as_str) {
        Some("api") => nonempty_json_string(value.get("key")),
        Some("oauth") => {
            value
                .get("expires")
                .and_then(serde_json::Value::as_u64)
                .is_some()
                && value
                    .get("access")
                    .is_some_and(serde_json::Value::is_string)
                && value
                    .get("refresh")
                    .is_some_and(serde_json::Value::is_string)
                && (nonempty_json_string(value.get("access"))
                    || nonempty_json_string(value.get("refresh")))
        }
        Some("wellknown") => {
            value.get("key").is_some_and(serde_json::Value::is_string)
                && value.get("token").is_some_and(serde_json::Value::is_string)
                && (nonempty_json_string(value.get("key"))
                    || nonempty_json_string(value.get("token")))
        }
        _ => false,
    }
}

fn nonempty_env(name: &str) -> Option<String> {
    std::env::var(name)
        .ok()
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty())
}

async fn provider_auth_status(provider: CodingProvider) -> Result<String> {
    match provider {
        CodingProvider::Codex => command_output("codex", &["login", "status"]).await,
        CodingProvider::Claude => command_output("claude", &["auth", "status", "--json"]).await,
        CodingProvider::OpenCode => command_output("opencode", &["providers", "list"]).await,
        _ => bail!("{provider:?} does not use an interactive provider login"),
    }
}

fn claude_auth_status_authenticated(output: &str) -> bool {
    match serde_json::from_str::<serde_json::Value>(output) {
        Ok(value) => value
            .get("loggedIn")
            .or_else(|| value.get("logged_in"))
            .and_then(serde_json::Value::as_bool)
            .unwrap_or(false),
        Err(_) => {
            let normalized = output.to_ascii_lowercase();
            !normalized.trim().is_empty()
                && !normalized.contains("not logged in")
                && !normalized.contains("logged out")
        }
    }
}

fn codex_auth_status_authenticated(output: &str) -> bool {
    if let Ok(value) = serde_json::from_str::<serde_json::Value>(output)
        && let Some(authenticated) = value
            .get("loggedIn")
            .or_else(|| value.get("logged_in"))
            .or_else(|| value.get("authenticated"))
            .and_then(serde_json::Value::as_bool)
    {
        return authenticated;
    }
    let normalized = output.to_ascii_lowercase();
    !normalized.trim().is_empty()
        && !normalized.contains("not logged in")
        && !normalized.contains("logged out")
        && !normalized.contains("unauthenticated")
        && (normalized.contains("logged in")
            || normalized.contains("authenticated")
            || normalized.contains("success"))
}

fn opencode_auth_status_authenticated(output: &str) -> bool {
    // `opencode providers list` renders its table header even when no provider
    // has credentials. A provider row is marked with a filled bullet; treat
    // that as the CLI's configured signal rather than merely accepting a
    // successful command exit.
    output.lines().any(|line| line.contains('●'))
}

async fn command_output(executable: &str, args: &[&str]) -> Result<String> {
    let mut command = Command::new(executable);
    command.args(args).stdin(Stdio::null());
    command_output_from(&mut command, executable).await
}

async fn command_output_from(command: &mut Command, executable: &str) -> Result<String> {
    let output = tokio::time::timeout(Duration::from_secs(8), command.output())
        .await
        .context("provider probe timed out")?
        .with_context(|| format!("{executable} is not installed"))?;
    if !output.status.success() {
        bail!("{executable} command failed");
    }
    let stdout = String::from_utf8_lossy(&output.stdout).trim().to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
    Ok(if stdout.is_empty() { stderr } else { stdout })
}

/// Whether `provider` already has credentials on this machine — an OAuth
/// session file written by its CLI, or an API key borg holds. Providers whose
/// credentials come from the environment are treated as configured; they fail
/// loudly at call time with their own message.
pub fn provider_credentials_present(provider: CodingProvider) -> bool {
    match provider {
        CodingProvider::Claude => {
            borg_provider::credentials::api_key(
                borg_provider::credentials::ApiKeyCredential::Anthropic,
            )
            .is_some()
                || provider_subscription_credentials_present(provider)
        }
        CodingProvider::Codex => {
            nonempty_env("OPENAI_API_KEY").is_some()
                || provider_subscription_credentials_present(provider)
        }
        CodingProvider::OpenCode => provider_subscription_credentials_present(provider),
        CodingProvider::Kimi => {
            nonempty_env("BORG_KIMI_API_KEY").is_some()
                || nonempty_env("MOONSHOT_API_KEY").is_some()
        }
        CodingProvider::OpenRouter => borg_provider::credentials::api_key(
            borg_provider::credentials::ApiKeyCredential::OpenRouter,
        )
        .is_some(),
        CodingProvider::OpenAiCompatible => {
            nonempty_env("BORG_OPENAI_COMPATIBLE_BASE_URL").is_some()
                || nonempty_env("BORG_OPENAI_COMPATIBLE_MODEL").is_some()
        }
    }
}

fn provider_login_command(provider: CodingProvider) -> Result<Command> {
    if provider.uses_native_harness() {
        bail!(
            "{provider:?} uses API credentials from the environment; configure the provider key and endpoint variables"
        );
    }
    let mut command = Command::new(provider.executable());
    match provider {
        CodingProvider::Codex => {
            command.args(["login", "--device-auth"]);
        }
        CodingProvider::Claude => {
            command.args(["auth", "login"]);
        }
        CodingProvider::OpenCode => {
            command.args(["providers", "login"]);
        }
        CodingProvider::Kimi | CodingProvider::OpenRouter | CodingProvider::OpenAiCompatible => {
            unreachable!("handled above")
        }
    };
    Ok(command)
}

pub async fn login_provider(provider: CodingProvider) -> Result<()> {
    let status = provider_login_command(provider)?
        .status()
        .await
        .with_context(|| format!("failed to start {} login", provider.executable()))?;
    if !status.success() {
        bail!("{} login exited with {status}", provider.executable());
    }
    let auth = provider_auth_status(provider).await.with_context(|| {
        format!(
            "{} login completed but auth status failed",
            provider.executable()
        )
    })?;
    anyhow::ensure!(
        match provider {
            CodingProvider::Claude => claude_auth_status_authenticated(&auth),
            _ => !auth.trim().is_empty(),
        },
        "{} login completed but no authenticated session is available",
        provider.executable()
    );
    if let Some(cache) = PROVIDER_CAPABILITIES_CACHE.get() {
        cache.lock().await.clear();
    }
    if let Some(cache) = PROVIDER_USAGE_CACHE.get() {
        cache.lock().await.clear();
    }
    Ok(())
}

async fn stream_provider_login_output(
    stream: impl AsyncRead + Unpin,
    tx: mpsc::UnboundedSender<String>,
) {
    let mut lines = BufReader::new(stream).lines();
    while let Ok(Some(line)) = lines.next_line().await {
        let _ = tx.send(line);
    }
}

/// Run a provider's browser/device login without requiring a terminal and
/// stream its user-facing output to a native frontend.
pub async fn login_provider_with_output(
    provider: CodingProvider,
    mut on_output: impl FnMut(&str) + Send,
) -> Result<()> {
    let mut command = provider_login_command(provider)?;
    command
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = command
        .spawn()
        .with_context(|| format!("failed to start {} login", provider.executable()))?;
    let stdout = child
        .stdout
        .take()
        .context("provider login stdout missing")?;
    let stderr = child
        .stderr
        .take()
        .context("provider login stderr missing")?;
    let (line_tx, mut line_rx) = mpsc::unbounded_channel();
    let stdout_task = tokio::spawn(stream_provider_login_output(stdout, line_tx.clone()));
    let stderr_task = tokio::spawn(stream_provider_login_output(stderr, line_tx.clone()));
    drop(line_tx);
    while let Some(line) = line_rx.recv().await {
        on_output(&line);
    }
    let _ = tokio::join!(stdout_task, stderr_task);
    let status = child
        .wait()
        .await
        .with_context(|| format!("failed to wait for {} login", provider.executable()))?;
    if !status.success() {
        bail!("{} login exited with {status}", provider.executable());
    }
    let auth = provider_auth_status(provider).await.with_context(|| {
        format!(
            "{} login completed but auth status failed",
            provider.executable()
        )
    })?;
    anyhow::ensure!(
        match provider {
            CodingProvider::Claude => claude_auth_status_authenticated(&auth),
            _ => !auth.trim().is_empty(),
        },
        "{} login completed but no authenticated session is available",
        provider.executable()
    );
    if let Some(cache) = PROVIDER_CAPABILITIES_CACHE.get() {
        cache.lock().await.clear();
    }
    if let Some(cache) = PROVIDER_USAGE_CACHE.get() {
        cache.lock().await.clear();
    }
    Ok(())
}

pub type HostExecutorFactory =
    Arc<dyn Fn(&HostConfig, &LaunchSession) -> Result<Arc<dyn AgentTurnExecutor>> + Send + Sync>;

fn default_host_executor_factory() -> HostExecutorFactory {
    Arc::new(|config, launch| {
        let executor = if launch.provider == CodingProvider::Kimi {
            crate::LocalAgentTurnExecutor::with_model_gateway(
                borg_provider::provider::ModelGateway::new(
                    endpoint(&config.server, "/api/remote/host/kimi/chat/completions"),
                    config.host_token.clone(),
                ),
            )
        } else {
            crate::LocalAgentTurnExecutor::default()
        };
        Ok(Arc::new(executor))
    })
}

pub async fn run_host(config_path: &Path) -> Result<()> {
    run_host_with_executor_factory(config_path, default_host_executor_factory()).await
}

pub async fn run_host_with_executor_factory(
    config_path: &Path,
    executor_factory: HostExecutorFactory,
) -> Result<()> {
    let config: HostConfig = serde_json::from_slice(
        &fs::read(config_path)
            .with_context(|| format!("failed to read {}", config_path.display()))?,
    )
    .with_context(|| format!("invalid host config {}", config_path.display()))?;
    config.validate()?;
    ensure_execution_boundary(&config)?;
    let client = Client::builder()
        .connect_timeout(Duration::from_secs(10))
        .timeout(Duration::from_secs(35))
        .build()?;
    let acknowledged = Arc::new(AtomicU64::new(0));
    let mut acknowledged_claim_token = None;
    let sessions: Arc<Mutex<HashMap<Uuid, mpsc::Sender<HostCommand>>>> =
        Arc::new(Mutex::new(HashMap::new()));
    let session_root = config_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join("sessions");
    let session_store =
        Arc::new(SqliteSessionStore::open(session_root.join("sessions.sqlite3")).await?);
    let receipts = Arc::new(SqliteReceiptStore::open(session_store.pool().clone()).await?);
    let mut capabilities =
        probe_capabilities_with_profile(config.roots.clone(), config.execution_profile).await;
    capabilities.resource_limits = config.resource_limits.clone();
    let mut capabilities_probed_at = Instant::now();
    let mut command_poll_backoff = RemoteRetryBackoff::default();
    loop {
        if capabilities_probed_at.elapsed() >= Duration::from_secs(300) {
            capabilities =
                probe_capabilities_with_profile(config.roots.clone(), config.execution_profile)
                    .await;
            capabilities.resource_limits = config.resource_limits.clone();
            capabilities_probed_at = Instant::now();
        }
        if let Err(error) = heartbeat(
            &client,
            &config,
            capabilities.clone(),
            acknowledged.load(Ordering::Relaxed),
            acknowledged_claim_token,
        )
        .await
        {
            tracing::warn!(%error, "remote host heartbeat failed; retrying");
            tokio::time::sleep(Duration::from_secs(2)).await;
            continue;
        }
        let response = client
            .get(endpoint(&config.server, "/api/remote/host/commands"))
            .bearer_auth(&config.host_token)
            .query(&[
                ("after", acknowledged.load(Ordering::Relaxed).to_string()),
                ("wait_seconds", "20".to_string()),
                ("protocol", "1".to_string()),
            ])
            .send()
            .await;
        let response = match response {
            Ok(response) => response,
            Err(error) => {
                let retry_delay = command_poll_backoff.next_delay(None);
                tracing::warn!(
                    %error,
                    retry_seconds = retry_delay.as_secs(),
                    "remote command poll failed; retrying"
                );
                tokio::time::sleep(retry_delay).await;
                continue;
            }
        };
        if response.status() == StatusCode::UNAUTHORIZED {
            bail!("remote host token was rejected; enroll this host again");
        }
        if !response.status().is_success() {
            let retry_delay = command_poll_backoff.next_delay(response_retry_after(&response));
            tracing::warn!(
                status = %response.status(),
                retry_seconds = retry_delay.as_secs(),
                "remote command poll failed"
            );
            tokio::time::sleep(retry_delay).await;
            continue;
        }
        command_poll_backoff.reset();
        let commands: CommandsResponse = response
            .json()
            .await
            .context("Borg returned invalid remote commands")?;
        for wire in commands.commands {
            let envelope = wire
                .into_legacy()
                .context("Borg returned an invalid agent runtime command envelope")?;
            let sequence = envelope.sequence;
            let claim_token = envelope.claim_token;
            let handled = dispatch(
                DispatchContext {
                    client: client.clone(),
                    config: config.clone(),
                    session_root: session_root.clone(),
                    sessions: sessions.clone(),
                    session_store: Arc::clone(&session_store),
                    receipts: Arc::clone(&receipts),
                    executor_factory: Arc::clone(&executor_factory),
                },
                envelope.command,
            )
            .await;
            if !handled {
                tokio::time::sleep(Duration::from_secs(2)).await;
                break;
            }
            if sequence >= acknowledged.load(Ordering::Relaxed) {
                acknowledged_claim_token = claim_token;
            }
            acknowledged.fetch_max(sequence, Ordering::Relaxed);
        }
    }
}

/// Mirror a terminal-owned session through the enrolled host relay.
///
/// The terminal remains the process owner and journal authority. This task
/// only registers the session, uploads its durable suffix, and forwards typed
/// commands from web/mobile clients.
pub async fn mirror_local_session(
    config_path: &Path,
    store: Arc<dyn crate::SessionStore>,
    session_id: Uuid,
    request: LaunchSession,
    commands: mpsc::Sender<HostCommand>,
    mut shutdown: watch::Receiver<bool>,
) -> Result<()> {
    let config: HostConfig = serde_json::from_slice(
        &fs::read(config_path)
            .with_context(|| format!("failed to read {}", config_path.display()))?,
    )
    .with_context(|| format!("invalid host config {}", config_path.display()))?;
    config.validate()?;
    ensure_execution_boundary(&config)?;
    let client = Client::builder()
        .connect_timeout(Duration::from_secs(3))
        .timeout(Duration::from_secs(35))
        .build()?;
    let registration = serde_json::json!({
        "session_id": session_id,
        "request": request,
    });
    let mut registration_backoff = RemoteRetryBackoff::default();
    let command_cursor = loop {
        let response = client
            .post(endpoint(&config.server, "/api/remote/host/sessions"))
            .bearer_auth(&config.host_token)
            .json(&registration)
            .send()
            .await;
        let retry_delay = match response {
            Ok(response) if response.status().is_success() => {
                let registered: RegisterSessionResponse = response
                    .json()
                    .await
                    .context("Borg returned an invalid local session registration")?;
                break merge_reconnect_cursors(
                    (
                        registered.command_cursor,
                        registered.event_cursor,
                        registered.live_revision,
                    ),
                    None,
                );
            }
            Ok(response) if response.status() == StatusCode::UNAUTHORIZED => {
                bail!("remote host token was rejected; enroll this host again");
            }
            Ok(response)
                if response.status().is_server_error()
                    || response.status() == StatusCode::TOO_MANY_REQUESTS =>
            {
                let retry_delay = registration_backoff.next_delay(response_retry_after(&response));
                tracing::warn!(
                    status = %response.status(),
                    retry_seconds = retry_delay.as_secs(),
                    "local session registration failed; retrying"
                );
                retry_delay
            }
            Ok(response) => {
                let status = response.status();
                let detail = response.text().await.unwrap_or_default().trim().to_string();
                if detail.is_empty() {
                    bail!("remote session registration was rejected ({status})");
                }
                bail!("remote session registration was rejected ({status}): {detail}");
            }
            Err(error) => {
                let retry_delay = registration_backoff.next_delay(None);
                tracing::warn!(
                    %error,
                    retry_seconds = retry_delay.as_secs(),
                    "local session registration failed; retrying"
                );
                retry_delay
            }
        };
        if wait_for_mirror_shutdown(&mut shutdown, retry_delay).await {
            return Ok(());
        }
    };

    let mut capabilities =
        probe_capabilities_with_profile(config.roots.clone(), config.execution_profile).await;
    capabilities.resource_limits = config.resource_limits.clone();
    let mut last_heartbeat = Instant::now() - Duration::from_secs(30);
    let (mut command_cursor, mut uploaded_sequence, mut uploaded_live_revision) = command_cursor;
    let mut command_claim_token = None;
    let mut event_retry_at = Instant::now();
    let mut shutdown_flush_pending = false;
    let mut command_poll_backoff = RemoteRetryBackoff::default();
    loop {
        if last_heartbeat.elapsed() >= Duration::from_secs(15) {
            if let Err(error) = heartbeat(
                &client,
                &config,
                capabilities.clone(),
                command_cursor,
                command_claim_token,
            )
            .await
            {
                tracing::warn!(%error, "local session heartbeat failed");
            } else {
                last_heartbeat = Instant::now();
            }
        }

        let mut caught_up = false;
        if Instant::now() >= event_retry_at {
            let pending = store
                .events_after(session_id, uploaded_sequence, 1_024)
                .await?;
            match upload_event_page(
                &client,
                &config,
                store.as_ref(),
                &pending,
                &mut uploaded_sequence,
                Duration::from_secs(5),
            )
            .await?
            {
                EventUploadOutcome::Complete => {
                    if upload_live_state(
                        &client,
                        &config,
                        store.as_ref(),
                        session_id,
                        &mut uploaded_live_revision,
                    )
                    .await?
                    {
                        caught_up = pending.len() < 1_024;
                        event_retry_at = Instant::now();
                    } else {
                        event_retry_at = Instant::now() + Duration::from_secs(2);
                    }
                }
                EventUploadOutcome::Retryable => {
                    event_retry_at = Instant::now() + Duration::from_secs(2);
                }
                EventUploadOutcome::Blocked { .. } => {
                    // Keep heartbeats and remote interrupt/stop commands alive
                    // without rereading the same irreducible event in a loop.
                    event_retry_at = Instant::now() + Duration::from_secs(300);
                }
            }
        }
        // A shutdown can arrive after this iteration read an empty suffix but
        // before the actor commits its terminal status. Only finish after one
        // complete upload pass that began after shutdown was observed.
        if shutdown_flush_pending && caught_up {
            return Ok(());
        }
        if *shutdown.borrow() {
            shutdown_flush_pending = true;
            let retry_delay = event_retry_at.saturating_duration_since(Instant::now());
            if retry_delay.is_zero() {
                tokio::task::yield_now().await;
            } else {
                tokio::time::sleep(retry_delay).await;
            }
            continue;
        }
        if caught_up && wait_for_mirror_shutdown(&mut shutdown, Duration::from_millis(250)).await {
            shutdown_flush_pending = true;
            continue;
        }

        let request = client
            .get(endpoint(&config.server, "/api/remote/host/commands"))
            .bearer_auth(&config.host_token)
            .query(&[
                ("after", command_cursor.to_string()),
                ("wait_seconds", "20".to_string()),
                ("protocol", "1".to_string()),
            ])
            .send();
        let response = tokio::select! {
            response = request => Some(response),
            changed = shutdown.changed() => {
                if changed.is_err() || *shutdown.borrow() {
                    None
                } else {
                    continue;
                }
            }
        };
        let Some(response) = response else {
            // Run one final loop so every journaled event, including the
            // terminal status, is durably uploaded before this task exits.
            shutdown_flush_pending = true;
            continue;
        };
        let response = match response {
            Ok(response) if response.status().is_success() => {
                command_poll_backoff.reset();
                response
            }
            Ok(response) if response.status() == StatusCode::UNAUTHORIZED => {
                bail!("remote host token was rejected; enroll this host again");
            }
            Ok(response) if response.status() == StatusCode::CONFLICT => {
                bail!(
                    "remote event replay conflicted with the durable remote journal: {}",
                    response.text().await.unwrap_or_default()
                );
            }
            Ok(response) => {
                let retry_delay = command_poll_backoff.next_delay(response_retry_after(&response));
                tracing::warn!(
                    status = %response.status(),
                    retry_seconds = retry_delay.as_secs(),
                    "local session command poll failed"
                );
                if wait_for_mirror_shutdown(&mut shutdown, retry_delay).await {
                    continue;
                }
                continue;
            }
            Err(error) => {
                let retry_delay = command_poll_backoff.next_delay(None);
                tracing::warn!(
                    %error,
                    retry_seconds = retry_delay.as_secs(),
                    "local session command poll failed"
                );
                if wait_for_mirror_shutdown(&mut shutdown, retry_delay).await {
                    continue;
                }
                continue;
            }
        };
        let response: CommandsResponse = response
            .json()
            .await
            .context("Borg returned invalid remote commands")?;
        for wire in response.commands {
            let envelope = wire
                .into_legacy()
                .context("Borg returned an invalid agent runtime command envelope")?;
            let sequence = envelope.sequence;
            let claim_token = envelope.claim_token;
            command_cursor = command_cursor.max(sequence);
            if envelope.command.session_id() == Some(session_id)
                && commands.send(envelope.command).await.is_err()
            {
                return Ok(());
            }
            let (acknowledged_sequence, acknowledged_token) = update_acknowledged_command(
                command_cursor,
                command_claim_token,
                sequence,
                claim_token,
            );
            command_cursor = acknowledged_sequence;
            command_claim_token = acknowledged_token;
        }
    }
}

async fn wait_for_mirror_shutdown(shutdown: &mut watch::Receiver<bool>, delay: Duration) -> bool {
    if *shutdown.borrow() {
        return true;
    }
    tokio::select! {
        _ = tokio::time::sleep(delay) => false,
        changed = shutdown.changed() => changed.is_err() || *shutdown.borrow(),
    }
}

fn update_acknowledged_command(
    current_sequence: u64,
    current_claim_token: Option<Uuid>,
    sequence: u64,
    claim_token: Option<Uuid>,
) -> (u64, Option<Uuid>) {
    if sequence >= current_sequence {
        (sequence, claim_token)
    } else {
        (current_sequence, current_claim_token)
    }
}

async fn heartbeat(
    client: &Client,
    config: &HostConfig,
    capabilities: HostCapabilities,
    acknowledged_command_sequence: u64,
    acknowledged_command_claim_token: Option<Uuid>,
) -> Result<()> {
    let response = client
        .post(endpoint(&config.server, "/api/remote/host/heartbeat"))
        .bearer_auth(&config.host_token)
        .json(&HostHeartbeat {
            name: config.name.clone(),
            platform: platform(),
            hostname: hostname(),
            capabilities,
            acknowledged_command_sequence,
            acknowledged_command_claim_token,
            identity: Some(RemoteHostIdentity {
                host_id: config.host_id,
                hostname: hostname(),
                platform: platform(),
            }),
        })
        .send()
        .await
        .context("failed to send remote host heartbeat")?;
    if !response.status().is_success() {
        bail!("remote host heartbeat failed with {}", response.status());
    }
    Ok(())
}

async fn load_session_sync(
    client: &Client,
    config: &HostConfig,
    session_id: Uuid,
) -> Result<SessionSyncResponse> {
    let response = client
        .get(endpoint(
            &config.server,
            &format!("/api/remote/host/sessions/{session_id}/sync"),
        ))
        .bearer_auth(&config.host_token)
        .send()
        .await
        .context("failed to load remote session sync cursor")?;
    if response.status() == StatusCode::UNAUTHORIZED {
        bail!("remote host token was rejected; enroll this host again");
    }
    if !response.status().is_success() {
        bail!(
            "remote session sync cursor failed with {}",
            response.status()
        );
    }
    response
        .json()
        .await
        .context("Borg returned an invalid session sync cursor")
}

struct DispatchContext {
    client: Client,
    config: HostConfig,
    session_root: PathBuf,
    sessions: Arc<Mutex<HashMap<Uuid, mpsc::Sender<HostCommand>>>>,
    session_store: Arc<SqliteSessionStore>,
    receipts: Arc<SqliteReceiptStore>,
    executor_factory: HostExecutorFactory,
}

async fn dispatch(context: DispatchContext, command: HostCommand) -> bool {
    let DispatchContext {
        client,
        config,
        session_root,
        sessions,
        session_store,
        receipts,
        executor_factory,
    } = context;
    if let HostCommand::ShellCommand { request } = &command {
        let Some(response) = shell_command_response(&receipts, &config, request).await else {
            return false;
        };
        return upload_host_action_result(
            &client,
            &config,
            "/api/remote/host/shell-command-results",
            response.request_id,
            &response,
        )
        .await;
    }
    if let HostCommand::OpenTerminal { request } = &command {
        let Some(response) = open_terminal_response(&receipts, &config, request).await else {
            return false;
        };
        return upload_host_action_result(
            &client,
            &config,
            "/api/remote/host/terminal-results",
            response.request_id,
            &response,
        )
        .await;
    }
    if let HostCommand::WorkspaceFilesystem { request } = &command {
        let Some(response) = filesystem_response(&receipts, &config, request).await else {
            return false;
        };
        let result = client
            .post(endpoint(
                &config.server,
                "/api/remote/host/filesystem-results",
            ))
            .bearer_auth(&config.host_token)
            .json(&response)
            .send()
            .await;
        let uploaded = match result {
            Ok(result) if result.status().is_success() => true,
            Ok(result) if matches!(result.status(), StatusCode::NOT_FOUND | StatusCode::GONE) => {
                tracing::warn!(
                    status = %result.status(),
                    request_id = %response.request_id,
                    "filesystem request no longer exists on the relay; acknowledging terminal result"
                );
                true
            }
            Ok(result) => {
                tracing::warn!(
                    status = %result.status(),
                    request_id = %response.request_id,
                    "filesystem result upload failed"
                );
                false
            }
            Err(error) => {
                tracing::warn!(
                    %error,
                    request_id = %response.request_id,
                    "filesystem result upload failed"
                );
                false
            }
        };
        return uploaded;
    }
    if let HostCommand::CancelWorkspaceFilesystem { .. } = &command {
        return true;
    }
    if let HostCommand::WorkspaceCommand { request } = &command {
        let Some(response) = workspace_command_response(&receipts, &config, request).await else {
            return false;
        };
        let result = client
            .post(endpoint(
                &config.server,
                "/api/remote/host/workspace-command-results",
            ))
            .bearer_auth(&config.host_token)
            .json(&response)
            .send()
            .await;
        let uploaded = match result {
            Ok(result) if result.status().is_success() => true,
            Ok(result) if matches!(result.status(), StatusCode::NOT_FOUND | StatusCode::GONE) => {
                tracing::warn!(
                    status = %result.status(),
                    request_id = %response.request_id,
                    "workspace command no longer exists on the relay; acknowledging terminal result"
                );
                true
            }
            Ok(result) => {
                tracing::warn!(
                    status = %result.status(),
                    request_id = %response.request_id,
                    "workspace command result upload failed"
                );
                false
            }
            Err(error) => {
                tracing::warn!(
                    %error,
                    request_id = %response.request_id,
                    "workspace command result upload failed"
                );
                false
            }
        };
        return uploaded;
    }
    if let HostCommand::CancelWorkspaceCommand { .. } = &command {
        return true;
    }
    if let HostCommand::Launch {
        session_id,
        request,
        attachment,
    } = command
    {
        if let Err(error) = validate_workspace_attachment(&config, session_id, attachment.as_ref())
        {
            tracing::error!(%error, %session_id, "failed to persist remote session launch");
            return false;
        }
        if let Err(error) =
            persist_launch_metadata(&session_store, session_id, &request, attachment.as_ref()).await
        {
            tracing::error!(%error, %session_id, "failed to persist remote session launch");
            return false;
        }
        {
            let sessions_guard = sessions.lock().await;
            if sessions_guard.contains_key(&session_id) {
                return true;
            }
            if sessions_guard.len() >= config.resource_limits.max_concurrent_sessions as usize {
                tracing::warn!(
                    %session_id,
                    active = sessions_guard.len(),
                    limit = config.resource_limits.max_concurrent_sessions,
                    "remote host session admission is at capacity"
                );
                // Leave the durable command unacknowledged so the relay can
                // retry it after another session releases its slot.
                return false;
            }
        }
        spawn_host_session(
            client,
            config,
            session_root,
            sessions,
            Arc::clone(&executor_factory),
            HostSessionLaunch {
                session_id,
                request: *request,
                attachment,
            },
        )
        .await;
        return true;
    }
    if let Some(session_id) = command.session_id() {
        let metadata = match load_launch_metadata(&session_store, session_id).await {
            Ok(metadata) => metadata,
            Err(error) => {
                tracing::error!(%error, %session_id, "failed to load stored launch metadata");
                return false;
            }
        };
        let attachment = metadata
            .as_ref()
            .and_then(|metadata| metadata.attachment.as_ref());
        if matches!(command, HostCommand::TeamPrompt { .. }) {
            tracing::warn!(%session_id, "rejected host-local team prompt from remote command queue");
            return true;
        }
        if let Some(attachment) = attachment.as_ref()
            && let Err(error) = authorize_workspace_command(attachment, &command)
        {
            tracing::warn!(%error, %session_id, "rejected unauthorized workspace command");
            // The command was handled by rejecting it. Leaving its envelope
            // unacknowledged would make the relay retry the same denied
            // command forever and head-of-line block every later command.
            return true;
        }
        let existing = { sessions.lock().await.get(&session_id).cloned() };
        let session = match existing {
            Some(session) => Some(session),
            None => {
                if let Some(metadata) = metadata {
                    if let Err(error) = validate_workspace_attachment(
                        &config,
                        session_id,
                        metadata.attachment.as_ref(),
                    ) {
                        tracing::error!(%error, %session_id, "stored launch attachment is invalid");
                        return false;
                    }
                    Some(
                        spawn_host_session(
                            client,
                            config,
                            session_root,
                            sessions,
                            Arc::clone(&executor_factory),
                            HostSessionLaunch {
                                session_id,
                                request: metadata.request,
                                attachment: metadata.attachment,
                            },
                        )
                        .await,
                    )
                } else {
                    None
                }
            }
        };
        if let Some(session) = session {
            session.send(command).await.ok();
        }
    }
    true
}

async fn upload_host_action_result<T: Serialize>(
    client: &Client,
    config: &HostConfig,
    path: &str,
    request_id: Uuid,
    response: &T,
) -> bool {
    match client
        .post(endpoint(&config.server, path))
        .bearer_auth(&config.host_token)
        .json(response)
        .send()
        .await
    {
        Ok(result) if result.status().is_success() => true,
        Ok(result) if matches!(result.status(), StatusCode::NOT_FOUND | StatusCode::GONE) => {
            tracing::warn!(status = %result.status(), %request_id, "remote host action is no longer present on the relay");
            true
        }
        Ok(result) => {
            tracing::warn!(status = %result.status(), %request_id, "remote host action result upload failed");
            false
        }
        Err(error) => {
            tracing::warn!(%error, %request_id, "remote host action result upload failed");
            false
        }
    }
}

async fn filesystem_response(
    receipts: &SqliteReceiptStore,
    config: &HostConfig,
    request: &WorkspaceFilesystemRequest,
) -> Option<WorkspaceFilesystemResponse> {
    let state = match receipts.load(request.request_id, request).await {
        Ok(state) => state,
        Err(error) => {
            tracing::warn!(%error, request_id = %request.request_id, "failed to read filesystem receipt");
            return None;
        }
    };
    match state {
        ReceiptState::Terminal(response) => Some(response),
        ReceiptState::Started => {
            let response = indeterminate_filesystem_response(
                request,
                "the host restarted after this mutation began; Borg will not replay it because its outcome cannot be proven",
            );
            persist_filesystem_terminal(receipts, request, &response).await
        }
        ReceiptState::Conflict => Some(indeterminate_filesystem_response(
            request,
            "request_id was already used for a different filesystem request",
        )),
        ReceiptState::Corrupt if request.operation.is_mutating() => {
            Some(indeterminate_filesystem_response(
                request,
                "the durable mutation receipt is unreadable; Borg will not replay the operation",
            ))
        }
        ReceiptState::Missing | ReceiptState::Corrupt => {
            if request.operation.is_mutating()
                && let Err(error) = receipts.begin(request.request_id, request).await
            {
                tracing::warn!(%error, request_id = %request.request_id, "failed to durably begin filesystem mutation");
                return None;
            }
            let response = execute_workspace_filesystem_with_limits(
                &config.roots,
                request.clone(),
                &config.resource_limits,
            )
            .await;
            persist_filesystem_terminal(receipts, request, &response).await
        }
    }
}

async fn persist_filesystem_terminal(
    receipts: &SqliteReceiptStore,
    request: &WorkspaceFilesystemRequest,
    response: &WorkspaceFilesystemResponse,
) -> Option<WorkspaceFilesystemResponse> {
    if let Err(error) = receipts.finish(request.request_id, request, response).await {
        tracing::warn!(%error, request_id = %request.request_id, "failed to persist terminal filesystem receipt");
        return None;
    }
    Some(response.clone())
}

fn indeterminate_filesystem_response(
    request: &WorkspaceFilesystemRequest,
    message: &str,
) -> WorkspaceFilesystemResponse {
    WorkspaceFilesystemResponse {
        request_id: request.request_id,
        workspace_id: request.workspace_id,
        outcome: WorkspaceFilesystemOutcome::Failure {
            code: WorkspaceFilesystemErrorCode::Indeterminate,
            message: message.to_string(),
            retryable: false,
        },
    }
}

