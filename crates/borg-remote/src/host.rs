async fn upload_event_payloads(
    client: &Client,
    config: &HostConfig,
    store: &dyn SessionStore,
    source_events: &[SessionEvent],
    remote_events: &[SessionEvent],
) -> Result<bool> {
    ensure!(
        source_events.len() == remote_events.len(),
        "remote payload preparation changed the event count"
    );
    let mut payloads = Vec::new();
    for (source_event, remote_event) in source_events.iter().zip(remote_events) {
        let target_session_id = remote_event.session_id;
        let source_refs = scoped_payload_refs(source_event, target_session_id);
        let remote_refs = scoped_payload_refs(remote_event, target_session_id);
        ensure!(
            source_refs.len() == remote_refs.len(),
            "remote payload preparation changed the payload count for event {}",
            source_event.id
        );
        for ((source_session_id, source), (remote_session_id, remote)) in
            source_refs.into_iter().zip(remote_refs)
        {
            ensure!(
                source_session_id == remote_session_id
                    && source.kind == remote.kind
                    && source.byte_len == remote.byte_len,
                "remote payload preparation changed payload metadata for event {}",
                source_event.id
            );
            payloads.push((remote_session_id, source, remote));
        }
    }
    let uploads = stream::iter(payloads)
        .map(|(session_id, source, remote)| async move {
            let bytes = store.load_payload(&source).await?;
            let response = client
                .post(endpoint(
                    &config.server,
                    &format!(
                        "/api/remote/host/sessions/{session_id}/payloads/{}",
                        remote.id
                    ),
                ))
                .bearer_auth(&config.host_token)
                .timeout(Duration::from_secs(30))
                .query(&[
                    ("kind", remote.kind.as_str().to_string()),
                    ("byte_len", remote.byte_len.to_string()),
                ])
                .body(bytes)
                .send()
                .await;
            match response {
                Ok(response) if response.status().is_success() => Ok(true),
                Ok(response) if response.status() == StatusCode::UNAUTHORIZED => {
                    bail!("remote host token was rejected; enroll this host again");
                }
                Ok(response) => {
                    tracing::warn!(
                        status = %response.status(),
                        %session_id,
                        payload_id = %remote.id,
                        source_payload_id = %source.id,
                        "remote session payload upload failed; retained for replay"
                    );
                    Ok(false)
                }
                Err(error) => {
                    tracing::warn!(
                        %error,
                        %session_id,
                        payload_id = %remote.id,
                        source_payload_id = %source.id,
                        "remote session payload upload failed; retained for replay"
                    );
                    Ok(false)
                }
            }
        })
        .buffered(MAX_CONCURRENT_EVENT_PAYLOAD_UPLOADS);
    futures::pin_mut!(uploads);
    while let Some(uploaded) = uploads.next().await {
        if !uploaded? {
            return Ok(false);
        }
    }
    Ok(true)
}

fn compact_event_payloads_for_upload(event: &SessionEvent) -> Result<SessionEvent> {
    let mut compact = event.clone();
    compact_event_payloads_in_place(&mut compact)?;
    Ok(compact)
}

fn compact_event_payloads_in_place(event: &mut SessionEvent) -> Result<()> {
    let event_id = event.id;
    match &mut event.kind {
        crate::SessionEventKind::ToolStarted {
            input, input_ref, ..
        } if input_ref.is_none() => {
            let bytes = serde_json::to_vec(input)?;
            if bytes.len() > crate::session_store::INLINE_SESSION_PAYLOAD_BYTES {
                let payload = derived_payload_ref(
                    event_id,
                    crate::SessionPayloadKind::ToolInput,
                    bytes.len(),
                );
                *input = crate::session_store::deferred_json_payload(&payload);
                *input_ref = Some(payload);
            }
        }
        crate::SessionEventKind::ToolCompleted {
            output,
            output_ref,
            input,
            input_ref,
            ..
        } => {
            if output_ref.is_none()
                && output.len() > crate::session_store::INLINE_SESSION_PAYLOAD_BYTES
            {
                let payload = derived_payload_ref(
                    event_id,
                    crate::SessionPayloadKind::ToolOutput,
                    output.len(),
                );
                *output = crate::session_store::deferred_text_payload(output, &payload);
                *output_ref = Some(payload);
            }
            if input_ref.is_none()
                && let Some(value) = input
            {
                let bytes = serde_json::to_vec(&*value)?;
                if bytes.len() > crate::session_store::INLINE_SESSION_PAYLOAD_BYTES {
                    let payload = derived_payload_ref(
                        event_id,
                        crate::SessionPayloadKind::ToolResultInput,
                        bytes.len(),
                    );
                    *value = crate::session_store::deferred_json_payload(&payload);
                    *input_ref = Some(payload);
                }
            }
        }
        crate::SessionEventKind::SubagentActivity {
            event: Some(child_event),
            ..
        } => compact_event_payloads_in_place(child_event)?,
        _ => {}
    }
    Ok(())
}

fn derived_payload_ref(
    event_id: Uuid,
    kind: crate::SessionPayloadKind,
    byte_len: usize,
) -> SessionPayloadRef {
    SessionPayloadRef {
        id: Uuid::new_v5(&event_id, kind.as_str().as_bytes()),
        kind,
        byte_len: u64::try_from(byte_len).unwrap_or(u64::MAX),
    }
}

fn prepare_event_upload(compact_event: &SessionEvent) -> SessionEvent {
    let mut remote_event = compact_event.clone();
    rekey_event_payloads(&mut remote_event, compact_event.session_id);
    remote_event
}

fn rekey_event_payloads(event: &mut SessionEvent, target_session_id: Uuid) {
    match &mut event.kind {
        crate::SessionEventKind::ToolStarted { input_ref, .. } => {
            rekey_remote_payload(target_session_id, input_ref);
        }
        crate::SessionEventKind::ToolCompleted {
            output_ref,
            input_ref,
            ..
        } => {
            rekey_remote_payload(target_session_id, output_ref);
            rekey_remote_payload(target_session_id, input_ref);
        }
        crate::SessionEventKind::SubagentActivity {
            event: Some(child_event),
            ..
        } => rekey_event_payloads(child_event, target_session_id),
        _ => {}
    }
}

fn rekey_remote_payload(session_id: Uuid, payload: &mut Option<SessionPayloadRef>) {
    if let Some(payload) = payload {
        payload.id = Uuid::new_v5(&session_id, payload.id.as_bytes());
    }
}

fn scoped_payload_refs(
    event: &SessionEvent,
    target_session_id: Uuid,
) -> Vec<(Uuid, SessionPayloadRef)> {
    let mut refs = event
        .kind
        .payload_refs()
        .into_iter()
        .map(|payload| (target_session_id, payload.clone()))
        .collect::<Vec<_>>();
    if let crate::SessionEventKind::SubagentActivity {
        event: Some(child_event),
        ..
    } = &event.kind
    {
        refs.extend(scoped_payload_refs(child_event, target_session_id));
    }
    refs
}

fn event_upload_ranges(events: &[SessionEvent]) -> Result<VecDeque<Range<usize>>> {
    let empty_batch_bytes = serde_json::to_vec(&relay_event_batch_payload(&[])?)?.len();
    let mut ranges = VecDeque::new();
    let mut start = 0;
    let mut batch_bytes = empty_batch_bytes;

    for (index, event) in events.iter().enumerate() {
        let separator_bytes = usize::from(index > start);
        let event_bytes =
            serde_json::to_vec(&AgentRuntimeEventEnvelope::from_event(event.clone()))?.len();
        if index > start
            && (index - start >= MAX_EVENT_BATCH_EVENTS
                || batch_bytes
                    .saturating_add(separator_bytes)
                    .saturating_add(event_bytes)
                    > TARGET_EVENT_BATCH_BYTES)
        {
            ranges.push_back(start..index);
            start = index;
            batch_bytes = empty_batch_bytes;
        }
        batch_bytes = batch_bytes
            .saturating_add(usize::from(index > start))
            .saturating_add(event_bytes);
    }
    if start < events.len() {
        ranges.push_back(start..events.len());
    }
    Ok(ranges)
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum EventUploadOutcome {
    Complete,
    Retryable,
    Blocked {
        session_id: Uuid,
        sequence: u64,
        event_kind: String,
        event_bytes: usize,
    },
}

async fn upload_event_page(
    client: &Client,
    config: &HostConfig,
    store: &dyn SessionStore,
    events: &[SessionEvent],
    uploaded_sequence: &mut u64,
    timeout: Duration,
) -> Result<EventUploadOutcome> {
    let compact_events = events
        .iter()
        .map(compact_event_payloads_for_upload)
        .collect::<Result<Vec<_>>>()?;
    let remote_events = compact_events
        .iter()
        .map(prepare_event_upload)
        .collect::<Vec<_>>();
    let mut ranges = event_upload_ranges(&remote_events)?;
    while let Some(range) = ranges.pop_front() {
        let batch = &remote_events[range.clone()];
        let runtime_batch = relay_event_batch_payload(batch)?;
        if !upload_event_payloads(client, config, store, &compact_events[range.clone()], batch)
            .await?
        {
            return Ok(EventUploadOutcome::Retryable);
        }
        let response = client
            .post(endpoint(&config.server, "/api/remote/host/events"))
            .bearer_auth(&config.host_token)
            .timeout(timeout)
            .query(&[("protocol", "1")])
            .json(&runtime_batch)
            .send()
            .await;
        match response {
            Ok(response) if response.status().is_success() => {
                if let Some(last) = batch.last() {
                    *uploaded_sequence = last.sequence;
                }
            }
            Ok(response)
                if response.status() == StatusCode::PAYLOAD_TOO_LARGE && batch.len() > 1 =>
            {
                let middle = range.start + range.len() / 2;
                tracing::warn!(
                    session_id = %batch[0].session_id,
                    first_sequence = batch[0].sequence,
                    last_sequence = batch[batch.len() - 1].sequence,
                    events = batch.len(),
                    "remote event batch was too large; splitting in order"
                );
                ranges.push_front(middle..range.end);
                ranges.push_front(range.start..middle);
            }
            Ok(response) if response.status() == StatusCode::PAYLOAD_TOO_LARGE => {
                let event_bytes = serde_json::to_vec(&runtime_batch)?.len();
                let event_kind = serde_json::to_value(&batch[0].kind)?
                    .get("type")
                    .and_then(serde_json::Value::as_str)
                    .unwrap_or("unknown")
                    .to_string();
                tracing::error!(
                    session_id = %batch[0].session_id,
                    sequence = batch[0].sequence,
                    %event_kind,
                    event_bytes,
                    "remote relay rejected irreducible session event; durable event was not skipped and sync is blocked"
                );
                return Ok(EventUploadOutcome::Blocked {
                    session_id: batch[0].session_id,
                    sequence: batch[0].sequence,
                    event_kind,
                    event_bytes,
                });
            }
            Ok(response) if response.status() == StatusCode::UNAUTHORIZED => {
                bail!("remote host token was rejected; enroll this host again");
            }
            Ok(response) if response.status() == StatusCode::CONFLICT => {
                bail!(
                    "remote event replay conflicted with the durable journal for session {}: {}",
                    batch[0].session_id,
                    response.text().await.unwrap_or_default()
                );
            }
            Ok(response)
                if response.status().is_client_error()
                    && response.status() != StatusCode::REQUEST_TIMEOUT
                    && response.status() != StatusCode::TOO_MANY_REQUESTS =>
            {
                let status = response.status();
                let detail = response
                    .text()
                    .await
                    .unwrap_or_default()
                    .chars()
                    .take(512)
                    .collect::<String>();
                let event_kind = serde_json::to_value(&batch[0].kind)?
                    .get("type")
                    .and_then(serde_json::Value::as_str)
                    .unwrap_or("unknown")
                    .to_string();
                tracing::error!(
                    %status,
                    %detail,
                    session_id = %batch[0].session_id,
                    sequence = batch[0].sequence,
                    %event_kind,
                    "remote relay permanently rejected a journal event; pausing replay"
                );
                return Ok(EventUploadOutcome::Blocked {
                    session_id: batch[0].session_id,
                    sequence: batch[0].sequence,
                    event_kind,
                    event_bytes: serde_json::to_vec(&batch[0])?.len(),
                });
            }
            Ok(response) => {
                let status = response.status();
                let detail = response
                    .text()
                    .await
                    .unwrap_or_default()
                    .chars()
                    .take(512)
                    .collect::<String>();
                tracing::warn!(
                    %status,
                    %detail,
                    session_id = %batch[0].session_id,
                    first_sequence = batch[0].sequence,
                    last_sequence = batch[batch.len() - 1].sequence,
                    events = batch.len(),
                    "remote event upload failed; journaled for replay"
                );
                return Ok(EventUploadOutcome::Retryable);
            }
            Err(error) => {
                tracing::warn!(
                    %error,
                    session_id = %batch[0].session_id,
                    first_sequence = batch[0].sequence,
                    last_sequence = batch[batch.len() - 1].sequence,
                    events = batch.len(),
                    "remote event upload failed; journaled for replay"
                );
                return Ok(EventUploadOutcome::Retryable);
            }
        }
    }
    Ok(EventUploadOutcome::Complete)
}

async fn upload_live_state(
    client: &Client,
    config: &HostConfig,
    store: &dyn SessionStore,
    session_id: Uuid,
    uploaded_revision: &mut u64,
) -> Result<bool> {
    let live = store
        .live_events_after(session_id, *uploaded_revision)
        .await?;
    if live.is_empty() {
        return Ok(true);
    }
    let response = client
        .post(endpoint(&config.server, "/api/remote/host/live-state"))
        .bearer_auth(&config.host_token)
        .json(&LiveStateBatch {
            session_id,
            events: &live,
        })
        .send()
        .await;
    match response {
        Ok(response) if response.status().is_success() => {
            *uploaded_revision = live
                .last()
                .map_or(*uploaded_revision, |event| event.revision);
            Ok(true)
        }
        Ok(response) if response.status() == StatusCode::UNAUTHORIZED => {
            bail!("remote host token was rejected; enroll this host again");
        }
        Ok(response) => {
            tracing::warn!(
                status = %response.status(),
                "remote live-state upload failed; retained for replay"
            );
            Ok(false)
        }
        Err(error) => {
            tracing::warn!(%error, "remote live-state upload failed; retained for replay");
            Ok(false)
        }
    }
}

pub fn default_host_config_path() -> PathBuf {
    std::env::var_os("BORG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".borg")))
        .or_else(|| dirs::home_dir().map(|home| home.join(".borg")))
        .unwrap_or_else(|| PathBuf::from(".borg"))
        .join("remote")
        .join("host.json")
}

pub async fn enroll_host(
    server: &str,
    token: &str,
    name: Option<&str>,
    roots: Vec<PathBuf>,
    config_path: &Path,
) -> Result<HostConfig> {
    let server = validate_server_url(server)?;
    ensure!(!token.trim().is_empty(), "host enrollment token is empty");
    let roots = canonical_roots(roots)?;
    let name = name
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .map(str::to_string)
        .unwrap_or_else(hostname);
    let execution_profile = configured_execution_profile();
    let resource_limits = configured_resource_limits();
    let capabilities = probe_capabilities_with_profile(roots.clone(), execution_profile).await;
    let response = Client::new()
        .post(endpoint(&server, "/api/remote/hosts/enroll"))
        .json(&EnrollRequest {
            token: token.to_string(),
            name: name.clone(),
            hostname: hostname(),
            platform: platform(),
            capabilities,
        })
        .send()
        .await
        .context("failed to contact Borg for host enrollment")?;
    if !response.status().is_success() {
        bail!(
            "host enrollment failed with {}: {}",
            response.status(),
            response.text().await.unwrap_or_default()
        );
    }
    let enrolled: EnrollResponse = response
        .json()
        .await
        .context("Borg returned an invalid host enrollment response")?;
    let config = HostConfig {
        server,
        host_id: enrolled.host.id,
        host_token: enrolled.host_token,
        name,
        roots,
        execution_profile,
        resource_limits,
    };
    config.validate()?;
    write_config(config_path, &config)?;
    Ok(config)
}

pub async fn probe_capabilities(roots: Vec<PathBuf>) -> HostCapabilities {
    probe_capabilities_with_profile(roots, configured_execution_profile()).await
}

async fn probe_capabilities_with_profile(
    roots: Vec<PathBuf>,
    execution_profile: HostExecutionProfile,
) -> HostCapabilities {
    let providers = probe_provider_capabilities_with_managed_kimi(true).await;
    HostCapabilities {
        protocol_version: REMOTE_PROTOCOL_VERSION,
        providers,
        roots,
        can_launch: true,
        can_run_shell_commands: true,
        can_open_terminal: terminal_emulator().is_some(),
        execution_profile,
        resource_limits: configured_resource_limits(),
        workspace_attachment: Some(workspace_attachment_capabilities()),
    }
}

fn configured_resource_limits() -> HostResourceLimits {
    // Keep the first hosted policy intentionally conservative and local. A
    // future control plane can negotiate lower ceilings, but it must never
    // increase what the host has declared here. Values are persisted in the
    // host config at enrollment so a later environment change cannot silently
    // widen an existing host's budget.
    let defaults = HostResourceLimits::default();
    HostResourceLimits {
        max_session_seconds: bounded_limit_env(
            "BORG_HOST_MAX_SESSION_SECONDS",
            defaults.max_session_seconds,
            1,
            7 * 24 * 60 * 60,
        ),
        max_runtime_execution_ms: bounded_limit_env(
            "BORG_HOST_MAX_RUNTIME_EXECUTION_MS",
            defaults.max_runtime_execution_ms,
            1,
            defaults.max_runtime_execution_ms,
        ),
        max_workspace_command_timeout_ms: bounded_limit_env(
            "BORG_HOST_MAX_COMMAND_TIMEOUT_MS",
            defaults.max_workspace_command_timeout_ms,
            1,
            defaults.max_workspace_command_timeout_ms,
        ),
        max_workspace_command_output_bytes: bounded_limit_env(
            "BORG_HOST_MAX_COMMAND_OUTPUT_BYTES",
            defaults.max_workspace_command_output_bytes,
            1,
            defaults.max_workspace_command_output_bytes,
        ),
        max_file_transfer_bytes: bounded_limit_env(
            "BORG_HOST_MAX_FILE_TRANSFER_BYTES",
            defaults.max_file_transfer_bytes,
            1,
            defaults.max_file_transfer_bytes,
        ),
        max_concurrent_sessions: bounded_limit_env(
            "BORG_HOST_MAX_CONCURRENT_SESSIONS",
            u64::from(defaults.max_concurrent_sessions),
            1,
            u64::from(defaults.max_concurrent_sessions),
        ) as u32,
        max_memory_bytes: bounded_limit_env(
            "BORG_HOST_MAX_MEMORY_BYTES",
            defaults.max_memory_bytes,
            128 * 1024 * 1024,
            64 * 1024 * 1024 * 1024,
        ),
        max_cpu_percent: bounded_limit_env(
            "BORG_HOST_MAX_CPU_PERCENT",
            u64::from(defaults.max_cpu_percent),
            1,
            1_600,
        ) as u32,
        max_processes: bounded_limit_env(
            "BORG_HOST_MAX_PROCESSES",
            u64::from(defaults.max_processes),
            16,
            4_096,
        ) as u32,
    }
}

fn bounded_limit_env(name: &str, default: u64, min: u64, max: u64) -> u64 {
    let Some(raw) = std::env::var_os(name) else {
        return default;
    };
    let raw = raw.to_string_lossy();
    match raw.trim().parse::<u64>() {
        Ok(value) => value.clamp(min, max),
        Err(error) => {
            tracing::warn!(name, value = %raw, %error, "invalid host resource limit; using default");
            default
        }
    }
}

fn configured_execution_profile() -> HostExecutionProfile {
    match std::env::var("BORG_HOST_EXECUTION_PROFILE")
        .ok()
        .map(|value| value.trim().to_ascii_lowercase())
        .as_deref()
    {
        Some("isolated_hosted" | "isolated" | "hosted") => HostExecutionProfile::IsolatedHosted,
        Some("trusted_user" | "trusted" | "local") | None => HostExecutionProfile::TrustedUser,
        Some(value) => {
            tracing::warn!(
                value,
                "invalid BORG_HOST_EXECUTION_PROFILE; using trusted_user"
            );
            HostExecutionProfile::TrustedUser
        }
    }
}

/// Probe every provider lane concurrently and return only secret-free
/// admission metadata. This is used at local launch and again at an enrolled
/// host boundary; a controller-supplied snapshot is never trusted.
pub async fn probe_provider_capabilities() -> Vec<ProviderCapability> {
    probe_provider_capabilities_with_managed_kimi(false).await
}

/// Build the provider admission snapshot from local executable and credential
/// metadata without starting every provider CLI. Detailed host/status probes
/// continue to validate commands and report versions.
pub async fn probe_provider_admission_capabilities() -> Vec<ProviderCapability> {
    probe_provider_admission_capabilities_with_managed_kimi(false).await
}

async fn probe_provider_admission_capabilities_with_managed_kimi(
    managed_kimi: bool,
) -> Vec<ProviderCapability> {
    probe_provider_capabilities_uncached(managed_kimi, ProviderProbeMode::Admission).await
}

async fn probe_provider_capabilities_with_managed_kimi(
    managed_kimi: bool,
) -> Vec<ProviderCapability> {
    let cache = PROVIDER_CAPABILITIES_CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut cache = cache.lock().await;
    if let Some((probed_at, providers)) = cache.get(&managed_kimi)
        && probed_at.elapsed() < PROVIDER_CAPABILITIES_CACHE_TTL
    {
        return providers.clone();
    }

    let providers =
        probe_provider_capabilities_uncached(managed_kimi, ProviderProbeMode::Detailed).await;
    cache.insert(managed_kimi, (Instant::now(), providers.clone()));
    providers
}

#[derive(Clone, Copy)]
enum ProviderProbeMode {
    Admission,
    Detailed,
}

async fn probe_provider_capabilities_uncached(
    managed_kimi: bool,
    mode: ProviderProbeMode,
) -> Vec<ProviderCapability> {
    let (codex, claude, opencode, kimi, openrouter, compatible) = tokio::join!(
        probe_provider(CodingProvider::Codex, managed_kimi, mode),
        probe_provider(CodingProvider::Claude, managed_kimi, mode),
        probe_provider(CodingProvider::OpenCode, managed_kimi, mode),
        probe_provider(CodingProvider::Kimi, managed_kimi, mode),
        probe_provider(CodingProvider::OpenRouter, managed_kimi, mode),
        probe_provider(CodingProvider::OpenAiCompatible, managed_kimi, mode),
    );
    refresh_provider_capability_usage(&[codex, claude, opencode, kimi, openrouter, compatible])
        .await
}

pub(crate) async fn refresh_provider_capability_usage(
    capabilities: &[ProviderCapability],
) -> Vec<ProviderCapability> {
    let has_subscription = |provider| {
        capabilities.iter().any(|capability| {
            capability.provider == provider
                && capability
                    .auth_methods
                    .contains(&ProviderAuthMethod::Subscription)
        })
    };
    let codex = async {
        if has_subscription(CodingProvider::Codex) {
            probe_provider_usage(CodingProvider::Codex).await
        } else {
            None
        }
    };
    let claude = async {
        if has_subscription(CodingProvider::Claude) {
            probe_provider_usage(CodingProvider::Claude).await
        } else {
            None
        }
    };
    let (codex, claude) = tokio::join!(codex, claude);
    capabilities
        .iter()
        .cloned()
        .map(|mut capability| {
            let usage = match capability.provider {
                CodingProvider::Codex => codex.clone(),
                CodingProvider::Claude => claude.clone(),
                _ => return capability,
            };
            if usage.is_some() {
                capability.usage = usage;
            }
            let exhausted = capability
                .usage
                .as_ref()
                .is_some_and(|usage| usage.availability == ProviderUsageAvailability::Exhausted);
            let alternate_route = capability.auth_methods.iter().any(|method| {
                matches!(
                    method,
                    ProviderAuthMethod::ApiKey | ProviderAuthMethod::Endpoint
                )
            });
            capability.can_spawn =
                capability.installed && capability.authenticated && (!exhausted || alternate_route);
            capability
        })
        .collect()
}

async fn probe_provider_usage(provider: CodingProvider) -> Option<ProviderUsage> {
    let cache = PROVIDER_USAGE_CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    if let Some((probed_at, usage)) = cache.lock().await.get(&provider)
        && probed_at.elapsed() < PROVIDER_CAPABILITIES_CACHE_TTL
    {
        return usage.clone();
    }
    let usage = match provider {
        CodingProvider::Codex => borg_provider::provider::read_codex_account_rate_limits()
            .await
            .ok()
            .map(codex_provider_usage),
        CodingProvider::Claude => borg_provider::provider::read_claude_account_rate_limits()
            .await
            .ok()
            .map(claude_provider_usage),
        _ => None,
    };
    cache
        .lock()
        .await
        .insert(provider, (Instant::now(), usage.clone()));
    usage
}

fn codex_provider_usage(limits: borg_provider::provider::CodexAccountRateLimits) -> ProviderUsage {
    let windows = [limits.primary, limits.secondary]
        .into_iter()
        .flatten()
        .map(|window| ProviderUsageWindow {
            label: provider_usage_window_label(window.window_duration_mins),
            used_percent: window.used_percent,
            resets_at: window
                .resets_at
                .and_then(|timestamp| DateTime::<Utc>::from_timestamp(timestamp, 0)),
            global: true,
        })
        .collect::<Vec<_>>();
    let exhausted = windows.iter().any(|window| window.used_percent >= 100);
    ProviderUsage {
        availability: if exhausted {
            ProviderUsageAvailability::Exhausted
        } else {
            ProviderUsageAvailability::Available
        },
        windows,
        detail: exhausted.then(|| "Codex subscription usage is exhausted".to_string()),
    }
}

fn claude_provider_usage(
    limits: borg_provider::provider::ClaudeAccountRateLimits,
) -> ProviderUsage {
    let exhausted = limits.rate_limits_available
        && limits
            .windows
            .iter()
            .any(|window| window.global && window.used_percent >= 100)
        && !limits.extra_usage_available;
    ProviderUsage {
        availability: if !limits.rate_limits_available {
            ProviderUsageAvailability::Unknown
        } else if exhausted {
            ProviderUsageAvailability::Exhausted
        } else {
            ProviderUsageAvailability::Available
        },
        windows: limits
            .windows
            .into_iter()
            .map(|window| ProviderUsageWindow {
                label: window.label,
                used_percent: window.used_percent,
                resets_at: window.resets_at,
                global: window.global,
            })
            .collect(),
        detail: if exhausted {
            Some("Claude subscription usage is exhausted".to_string())
        } else if limits.extra_usage_available {
            Some("Claude extra usage is available after plan limits".to_string())
        } else {
            None
        },
    }
}

fn provider_usage_window_label(duration_mins: u64) -> String {
    match duration_mins {
        10_080 => "Weekly".to_string(),
        1_440 => "Daily".to_string(),
        300 => "5-hour".to_string(),
        60 => "Hourly".to_string(),
        mins if mins % 1_440 == 0 => format!("{}-day", mins / 1_440),
        mins if mins % 60 == 0 => format!("{}-hour", mins / 60),
        mins => format!("{mins}-minute"),
    }
}

