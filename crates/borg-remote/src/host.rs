fn discard_serialized_extension_roots(launch: &mut LaunchSession) {
    if !launch.extension_skill_roots.is_empty() {
        tracing::debug!(
            count = launch.extension_skill_roots.len(),
            "discarding controller-supplied extension roots at host boundary"
        );
        // A remote controller may only request a session. The host-side
        // executor factory discovers its own active/trusted Blu catalog; no
        // serialized path is allowed to become a host filesystem capability.
        launch.extension_skill_roots.clear();
    }
}

struct HostSessionLaunch {
    session_id: Uuid,
    request: LaunchSession,
    attachment: Option<WorkspaceAttachment>,
}

async fn spawn_host_session(
    client: Client,
    config: HostConfig,
    session_root: PathBuf,
    sessions: Arc<Mutex<HashMap<Uuid, mpsc::Sender<HostCommand>>>>,
    executor_factory: HostExecutorFactory,
    launch: HostSessionLaunch,
) -> mpsc::Sender<HostCommand> {
    let session_id = launch.session_id;
    let (tx, rx) = mpsc::channel(64);
    sessions.lock().await.insert(session_id, tx.clone());
    let sessions_for_cleanup = sessions.clone();
    tokio::spawn(async move {
        if let Err(error) =
            run_session(client, config, session_root, executor_factory, launch, rx).await
        {
            tracing::error!(session_id = %session_id, %error, "remote agent session failed");
        }
        sessions_for_cleanup.lock().await.remove(&session_id);
    });
    tx
}

async fn run_session(
    client: Client,
    config: HostConfig,
    session_root: PathBuf,
    executor_factory: HostExecutorFactory,
    launch_request: HostSessionLaunch,
    commands: mpsc::Receiver<HostCommand>,
) -> Result<()> {
    let HostSessionLaunch {
        session_id,
        request: mut launch,
        attachment,
    } = launch_request;
    launch.cwd = validate_host_cwd(&config.roots, &launch.cwd)?;
    discard_serialized_extension_roots(&mut launch);
    // The controller may have sent a stale or malicious capability snapshot.
    // Authentication is a host-local fact, so refresh it after the workspace
    // boundary and before constructing the child coordinator.
    launch.capabilities.provider_capabilities =
        probe_provider_admission_capabilities_with_managed_kimi(true).await;
    launch.capabilities.resource_limits = Some(config.resource_limits.clone());
    if let Some(context) = fetch_runtime_mcp_context(&client, &config, session_id).await? {
        launch.capabilities.runtime_mcp_context = Some(context);
    }
    let lock_path = session_root.join(format!("{session_id}.lock"));
    let writer = SessionWriterLease::acquire(&lock_path)?;
    let sqlite_store =
        Arc::new(SqliteSessionStore::open(session_root.join("sessions.sqlite3")).await?);
    let workspace_attachment = attachment
        .as_ref()
        .and_then(|attachment| attachment.workspace_id.zip(attachment.participant_id));
    if !sqlite_store.contains_session(session_id).await? {
        if let Some((workspace_id, participant_id)) = workspace_attachment {
            sqlite_store
                .create_session_in_workspace_as(session_id, workspace_id, participant_id)
                .await?;
        } else {
            sqlite_store.create_session(session_id).await?;
        }
    }
    if let Some((workspace_id, participant_id)) = workspace_attachment {
        sqlite_store
            .attach_workspace(crate::SessionWorkspaceBinding {
                session_id,
                workspace_id,
                participant_id,
                host_id: Some(config.host_id),
                attached_at: Utc::now(),
            })
            .await?;
    }
    let workspace_store = sqlite_store.workspace_store().await?;
    if let (Some(store), Some((workspace_id, participant_id))) =
        (workspace_store.as_ref(), workspace_attachment)
    {
        let human_display_name = std::env::var("USER").unwrap_or_else(|_| "Local user".to_string());
        let human_participant_id = crate::local_human_participant_id(&human_display_name);
        let workspace_name = launch
            .cwd
            .file_name()
            .and_then(|name| name.to_str())
            .filter(|name| !name.is_empty())
            .unwrap_or("Borg workspace");
        store
            .ensure_execution_workspace(
                workspace_id,
                workspace_name,
                human_participant_id,
                &human_display_name,
                participant_id,
                launch.name.as_deref().unwrap_or("Borg"),
            )
            .await?;
    }
    let store: Arc<dyn SessionStore> = sqlite_store.clone();
    let cursor = load_session_sync(&client, &config, session_id).await?;
    let mut sync = JournalSync {
        uploaded_sequence: cursor.event_cursor,
        uploaded_live_revision: cursor.live_revision,
        uploaded_workspace_sequence: 0,
        workspace_relay_available: attachment.is_some(),
        next_workspace_roster_sync: Instant::now(),
        retry_at: Instant::now(),
    };
    flush_pending(&client, &config, store.as_ref(), session_id, &mut sync).await?;
    flush_workspace_messages(
        &client,
        &config,
        sqlite_store.as_ref(),
        workspace_store.as_ref(),
        session_id,
        attachment.as_ref(),
        &mut sync,
    )
    .await?;
    let (event_tx, mut event_rx) = mpsc::channel(256);
    let actor_session_root = session_root.clone();
    let actor_store = Arc::clone(&sqlite_store);
    let executor = executor_factory(&config, &launch)?;
    let lsp_policy = match config.execution_profile {
        HostExecutionProfile::IsolatedHosted => LspPathPolicy::session_workspace(),
        HostExecutionProfile::TrustedUser => LspPathPolicy::authorized_roots(config.roots.clone()),
    };
    let actor = tokio::spawn(async move {
        run_agent_session_with_store_and_writer_and_lsp_policy(
            &actor_session_root,
            session_id,
            launch,
            commands,
            event_tx,
            executor,
            actor_store,
            writer,
            lsp_policy,
        )
        .await
    });
    let session_deadline = tokio::time::sleep(Duration::from_secs(
        config.resource_limits.max_session_seconds,
    ));
    tokio::pin!(session_deadline);
    let mut session_expired = false;
    loop {
        tokio::select! {
            event = event_rx.recv() => {
                if event.is_none() {
                    break;
                }
            }
            _ = &mut session_deadline => {
                // The host-owned duration is a hard ceiling. Abort the actor
                // so a controller cannot keep an admitted session alive by
                // withholding prompts; the local journal remains available
                // for the normal recovery path.
                session_expired = true;
                actor.abort();
                break;
            }
            _ = tokio::time::sleep(Duration::from_secs(1)) => {}
        }
        flush_pending(&client, &config, store.as_ref(), session_id, &mut sync).await?;
        flush_workspace_messages(
            &client,
            &config,
            sqlite_store.as_ref(),
            workspace_store.as_ref(),
            session_id,
            attachment.as_ref(),
            &mut sync,
        )
        .await?;
    }
    if session_expired {
        let _ = actor.await;
        flush_pending(&client, &config, store.as_ref(), session_id, &mut sync).await?;
        flush_workspace_messages(
            &client,
            &config,
            sqlite_store.as_ref(),
            workspace_store.as_ref(),
            session_id,
            attachment.as_ref(),
            &mut sync,
        )
        .await?;
        bail!(
            "host session exceeded the configured {} second limit",
            config.resource_limits.max_session_seconds
        );
    }
    actor.await.context("agent session task failed")??;
    flush_pending(&client, &config, store.as_ref(), session_id, &mut sync).await?;
    flush_workspace_messages(
        &client,
        &config,
        sqlite_store.as_ref(),
        workspace_store.as_ref(),
        session_id,
        attachment.as_ref(),
        &mut sync,
    )
    .await
}

async fn fetch_runtime_mcp_context(
    client: &Client,
    config: &HostConfig,
    session_id: Uuid,
) -> Result<Option<RuntimeMcpContext>> {
    let response = client
        .get(endpoint(
            &config.server,
            &format!("/api/remote/host/sessions/{session_id}/runtime-context"),
        ))
        .header("x-borg-runtime-secret-refs", "1")
        .bearer_auth(&config.host_token)
        .send()
        .await
        .context("failed to fetch the Web runtime MCP context")?;
    if response.status() == StatusCode::NOT_FOUND {
        // Older Web control planes do not expose this optional capability
        // endpoint; the canonical actor remains usable with host-local tools.
        return Ok(None);
    }
    if !response.status().is_success() {
        bail!(
            "Web runtime MCP context fetch failed with {}: {}",
            response.status(),
            response.text().await.unwrap_or_default()
        );
    }
    let mut context: RuntimeMcpContext = response
        .json()
        .await
        .context("Web returned an invalid runtime MCP context")?;
    validate_runtime_mcp_context(
        &context,
        config.execution_profile,
        Some(session_id),
        Some(config.host_id),
    )?;
    resolve_runtime_mcp_secrets(client, config, session_id, &mut context).await?;
    Ok(Some(context))
}

async fn resolve_runtime_mcp_secrets(
    client: &Client,
    config: &HostConfig,
    session_id: Uuid,
    context: &mut RuntimeMcpContext,
) -> Result<()> {
    const MAX_SECRET_REFS: usize = 128;
    let mut refs = context
        .external_servers
        .iter()
        .flat_map(|server| server.secret_refs.values().cloned())
        .collect::<Vec<_>>();
    if let Some(reference) = context.api_token_ref.clone() {
        refs.push(reference);
    }
    refs.sort();
    refs.dedup();
    ensure!(
        refs.len() <= MAX_SECRET_REFS,
        "Web runtime MCP context contains too many secret references"
    );
    if refs.is_empty() {
        return Ok(());
    }

    let response = client
        .post(endpoint(
            &config.server,
            &format!("/api/remote/host/sessions/{session_id}/runtime-context/secrets"),
        ))
        .bearer_auth(&config.host_token)
        .json(&RuntimeMcpSecretRequest { refs: &refs })
        .send()
        .await
        .context("failed to resolve Web runtime MCP secret references")?;
    if response.status() == StatusCode::NOT_FOUND {
        bail!(
            "Web runtime MCP grant contains secret references but the control plane does not support secret resolution"
        );
    }
    if !response.status().is_success() {
        bail!(
            "Web runtime MCP secret resolution failed with {}: {}",
            response.status(),
            response.text().await.unwrap_or_default()
        );
    }
    let resolved: RuntimeMcpSecretResponse = response
        .json()
        .await
        .context("Web returned an invalid runtime MCP secret response")?;
    ensure!(
        resolved.values.len() == refs.len()
            && refs
                .iter()
                .all(|reference| resolved.values.contains_key(reference)),
        "Web runtime MCP secret response did not resolve exactly the requested references"
    );
    ensure!(
        resolved.values.values().all(|value| !value.is_empty()),
        "Web runtime MCP secret response contains an empty value"
    );

    for server in &mut context.external_servers {
        for (env_key, reference) in std::mem::take(&mut server.secret_refs) {
            let value = resolved
                .values
                .get(&reference)
                .expect("validated runtime MCP secret reference")
                .clone();
            server.env.insert(env_key, value);
        }
    }
    if let Some(reference) = context.api_token_ref.take() {
        context.api_token = resolved.values.get(&reference).cloned();
        ensure!(
            context
                .api_token
                .as_deref()
                .is_some_and(|value| !value.is_empty()),
            "Web runtime MCP API token reference resolved to an empty value"
        );
    }
    Ok(())
}

fn validate_runtime_mcp_context(
    context: &RuntimeMcpContext,
    execution_profile: HostExecutionProfile,
    expected_session_id: Option<Uuid>,
    expected_host_id: Option<Uuid>,
) -> Result<()> {
    const MAX_SERVERS: usize = 64;
    const MAX_SERVER_ARGS: usize = 128;
    const MAX_SERVER_ENV: usize = 128;
    const MAX_ALLOWED_TOOLS: usize = 256;
    const MAX_SECRET_REFS: usize = 128;
    const MAX_SERVER_TEXT_BYTES: usize = 32 * 1024;
    ensure!(
        context.external_servers.len() <= MAX_SERVERS,
        "Web runtime MCP context contains too many external servers"
    );
    let secret_ref_count = context
        .external_servers
        .iter()
        .map(|server| server.secret_refs.len())
        .sum::<usize>()
        + usize::from(context.api_token_ref.is_some());
    ensure!(
        secret_ref_count <= MAX_SECRET_REFS,
        "Web runtime MCP context contains too many secret references"
    );
    if let Some(reference) = &context.api_token_ref {
        ensure!(
            !reference.trim().is_empty() && reference.len() <= MAX_SERVER_TEXT_BYTES,
            "runtime MCP API token reference is invalid"
        );
    }
    if let Some(expected_session_id) = expected_session_id
        && let Some(session_id) = context.session_id
    {
        ensure!(
            session_id == expected_session_id,
            "Web runtime MCP context is bound to a different session"
        );
    }
    if let Some(expected_host_id) = expected_host_id
        && let Some(host_id) = context.host_id
    {
        ensure!(
            host_id == expected_host_id,
            "Web runtime MCP context is bound to a different host"
        );
    }
    if let Some(issued_at) = context.issued_at {
        ensure!(
            issued_at <= Utc::now() + chrono::Duration::minutes(5),
            "Web runtime MCP context was issued in the future"
        );
    }
    if let Some(expires_at) = context.expires_at {
        ensure!(
            context
                .issued_at
                .is_none_or(|issued_at| expires_at > issued_at),
            "Web runtime MCP context has an invalid lifetime"
        );
        ensure!(
            expires_at > Utc::now(),
            "Web runtime MCP context has expired"
        );
        ensure!(
            expires_at <= Utc::now() + chrono::Duration::days(7),
            "Web runtime MCP context lifetime is too long"
        );
    }
    let allowed_commands = isolated_mcp_command_allowlist();
    let mut names = HashSet::new();
    for server in &context.external_servers {
        ensure!(
            !server.name.trim().is_empty(),
            "runtime MCP server name is empty"
        );
        ensure!(
            names.insert(server.name.clone()),
            "runtime MCP context contains duplicate server name `{}`",
            server.name
        );
        ensure!(
            !server.command.trim().is_empty(),
            "runtime MCP server `{}` has no executable command",
            server.name
        );
        ensure!(
            server.args.len() <= MAX_SERVER_ARGS,
            "runtime MCP server `{}` contains too many arguments",
            server.name
        );
        ensure!(
            server.env.len().saturating_add(server.secret_refs.len()) <= MAX_SERVER_ENV,
            "runtime MCP server `{}` contains too many environment entries",
            server.name
        );
        ensure!(
            server.allowed_tools.len() <= MAX_ALLOWED_TOOLS,
            "runtime MCP server `{}` contains too many allowed tools",
            server.name
        );
        for (env_key, reference) in &server.secret_refs {
            ensure!(
                !env_key.trim().is_empty(),
                "runtime MCP secret environment key is empty"
            );
            ensure!(
                !reference.trim().is_empty() && reference.len() <= MAX_SERVER_TEXT_BYTES,
                "runtime MCP secret reference is invalid"
            );
        }
        if execution_profile == HostExecutionProfile::IsolatedHosted {
            ensure!(
                isolated_mcp_command_allowed(&server.command, &allowed_commands),
                "isolated hosted worker rejected MCP executable `{}`; allow it with BORG_ISOLATED_ALLOWED_MCP_COMMANDS",
                server.command
            );
        }
        for value in std::iter::once(&server.name)
            .chain(std::iter::once(&server.command))
            .chain(server.args.iter())
            .chain(server.env.keys())
            .chain(server.env.values())
            .chain(server.secret_refs.keys())
            .chain(server.secret_refs.values())
            .chain(server.allowed_tools.iter())
        {
            ensure!(
                value.len() <= MAX_SERVER_TEXT_BYTES,
                "runtime MCP server field is too large"
            );
            ensure!(
                !value.chars().any(char::is_control),
                "runtime MCP server field contains control characters"
            );
        }
    }
    Ok(())
}

fn isolated_mcp_command_allowlist() -> Vec<String> {
    std::env::var("BORG_ISOLATED_ALLOWED_MCP_COMMANDS")
        .ok()
        .into_iter()
        .flat_map(|value| {
            value
                .split(',')
                .map(str::trim)
                .filter(|item| !item.is_empty())
                .map(str::to_string)
                .collect::<Vec<_>>()
        })
        .collect()
}

fn isolated_mcp_command_allowed(command: &str, allowlist: &[String]) -> bool {
    let command = Path::new(command);
    let basename = command
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_default();
    // The scoped Borg MCP server is part of the canonical host contract. It
    // may be installed in a deployment-specific directory, so its basename
    // is the stable identity rather than a path from the controller.
    if matches!(basename, "borg-mcp" | "borg-mcp.exe") {
        return true;
    }
    allowlist
        .iter()
        .any(|allowed| allowed == command.to_string_lossy().as_ref() || allowed == basename)
}

struct JournalSync {
    uploaded_sequence: u64,
    uploaded_live_revision: u64,
    uploaded_workspace_sequence: u64,
    workspace_relay_available: bool,
    next_workspace_roster_sync: Instant,
    retry_at: Instant,
}

async fn flush_workspace_messages(
    client: &Client,
    config: &HostConfig,
    session_store: &SqliteSessionStore,
    workspace_store: Option<&SqliteWorkspaceStore>,
    session_id: Uuid,
    attachment: Option<&WorkspaceAttachment>,
    sync: &mut JournalSync,
) -> Result<()> {
    if !sync.workspace_relay_available || Instant::now() < sync.retry_at {
        return Ok(());
    }
    let Some(store) = workspace_store else {
        return Ok(());
    };
    let Some((workspace_id, participant_id)) =
        attachment.and_then(|attachment| attachment.workspace_id.zip(attachment.participant_id))
    else {
        return Ok(());
    };
    if Instant::now() >= sync.next_workspace_roster_sync {
        let response = client
            .get(endpoint(
                &config.server,
                &format!("/api/remote/host/sessions/{session_id}/workspace/participants"),
            ))
            .bearer_auth(&config.host_token)
            .send()
            .await;
        match response {
            Ok(response) if response.status().is_success() => {
                let roster: RelayWorkspaceRoster = response
                    .json()
                    .await
                    .context("borg.ml returned an invalid workspace roster")?;
                for remote in roster.participants {
                    store
                        .upsert_relay_roster_entry(
                            workspace_id,
                            Participant {
                                id: remote.id,
                                display_name: remote.display_name,
                                kind: remote.kind,
                                created_at: remote.created_at,
                            },
                            remote.role,
                        )
                        .await?;
                }
                sync.next_workspace_roster_sync = Instant::now() + Duration::from_secs(30);
            }
            Ok(response) if response.status() == StatusCode::NOT_FOUND => {
                sync.workspace_relay_available = false;
                return Ok(());
            }
            Ok(response) => {
                tracing::warn!(
                    status = %response.status(),
                    "workspace roster synchronization failed"
                );
                sync.next_workspace_roster_sync = Instant::now() + Duration::from_secs(5);
            }
            Err(error) => {
                tracing::warn!(%error, "workspace roster synchronization failed");
                sync.next_workspace_roster_sync = Instant::now() + Duration::from_secs(5);
            }
        }
    }
    const PAGE_SIZE: usize = 256;
    loop {
        let events = store
            .replay(
                workspace_id,
                participant_id,
                sync.uploaded_workspace_sequence,
                PAGE_SIZE,
            )
            .await?;
        let caught_up = events.len() < PAGE_SIZE;
        for event in events {
            if event.author_id == participant_id
                && let WorkspaceEventKind::Message { message, mode } = &event.kind
            {
                let (audience, audience_role, mut recipients) = match &message.audience {
                    Audience::Workspace => ("workspace", None, Vec::new()),
                    Audience::Participants { participants } => {
                        ("participants", None, participants.clone())
                    }
                    Audience::Role { role } => {
                        ("role", Some(serde_json::to_value(role)?), Vec::new())
                    }
                    Audience::Direct { participant } => ("direct", None, vec![*participant]),
                };
                if matches!(
                    &message.audience,
                    Audience::Direct { .. } | Audience::Participants { .. }
                ) {
                    let mut cloud_recipients = Vec::with_capacity(recipients.len());
                    for recipient in recipients {
                        let local_only = session_store
                            .workspace_binding(recipient)
                            .await?
                            .is_some_and(|binding| binding.host_id.is_none());
                        if !local_only {
                            cloud_recipients.push(recipient);
                        }
                    }
                    recipients = cloud_recipients;
                    if recipients.is_empty() {
                        sync.uploaded_workspace_sequence = event.sequence;
                        continue;
                    }
                }
                let response = client
                    .post(endpoint(
                        &config.server,
                        &format!("/api/remote/host/sessions/{session_id}/workspace/messages"),
                    ))
                    .bearer_auth(&config.host_token)
                    .json(&serde_json::json!({
                        "text": message.body.text,
                        "audience": audience,
                        "audience_role": audience_role,
                        "recipient_participant_ids": recipients,
                        "mentions": message.body.mentions,
                        "thread_id": message.thread_id,
                        "reply_to_message_id": message.reply_to_message_id,
                        "idempotency_key": event.id.to_string(),
                        "delivery_mode": mode,
                        "metadata": {
                            "local_workspace_event_id": event.id,
                            "local_workspace_sequence": event.sequence,
                        }
                    }))
                    .send()
                    .await;
                match response {
                    Ok(response) if response.status().is_success() => {}
                    Ok(response) if response.status() == StatusCode::NOT_FOUND => {
                        tracing::warn!(
                            "borg.ml does not expose the workspace relay endpoint; disabling it for this session"
                        );
                        sync.workspace_relay_available = false;
                        return Ok(());
                    }
                    Ok(response) => {
                        tracing::warn!(
                            status = %response.status(),
                            workspace_event_id = %event.id,
                            "workspace message relay rejected an event"
                        );
                        sync.retry_at = Instant::now() + Duration::from_secs(2);
                        return Ok(());
                    }
                    Err(error) => {
                        tracing::warn!(
                            %error,
                            workspace_event_id = %event.id,
                            "workspace message relay upload failed"
                        );
                        sync.retry_at = Instant::now() + Duration::from_secs(2);
                        return Ok(());
                    }
                }
            }
            sync.uploaded_workspace_sequence = event.sequence;
        }
        if caught_up {
            break;
        }
    }
    Ok(())
}

async fn flush_pending(
    client: &Client,
    config: &HostConfig,
    store: &dyn SessionStore,
    session_id: Uuid,
    sync: &mut JournalSync,
) -> Result<()> {
    if Instant::now() < sync.retry_at {
        return Ok(());
    }
    const PAGE_SIZE: usize = 1_024;
    loop {
        let pending = store
            .events_after(session_id, sync.uploaded_sequence, PAGE_SIZE)
            .await?;
        let caught_up = pending.len() < PAGE_SIZE;
        match upload_event_page(
            client,
            config,
            store,
            &pending,
            &mut sync.uploaded_sequence,
            Duration::from_secs(3),
        )
        .await?
        {
            EventUploadOutcome::Complete => {}
            EventUploadOutcome::Retryable => {
                sync.retry_at = Instant::now() + Duration::from_secs(2);
                return Ok(());
            }
            EventUploadOutcome::Blocked { .. } => {
                // Preserve the actor and command receiver. A later binary or
                // relay limit change can resume from this exact cursor.
                sync.retry_at = Instant::now() + Duration::from_secs(300);
                return Ok(());
            }
        }
        if caught_up {
            break;
        }
    }
    if !upload_live_state(
        client,
        config,
        store,
        session_id,
        &mut sync.uploaded_live_revision,
    )
    .await?
    {
        sync.retry_at = Instant::now() + Duration::from_secs(2);
        return Ok(());
    }
    sync.retry_at = Instant::now();
    Ok(())
}

fn validate_host_cwd(roots: &[PathBuf], requested: &Path) -> Result<PathBuf> {
    let cwd = requested
        .canonicalize()
        .with_context(|| format!("session directory does not exist: {}", requested.display()))?;
    if !cwd.is_dir() {
        bail!("session path is not a directory: {}", cwd.display());
    }
    if !roots.is_empty() && !roots.iter().any(|root| cwd.starts_with(root)) {
        bail!("session directory is outside this host's enrolled roots");
    }
    Ok(cwd)
}

fn canonical_roots(roots: Vec<PathBuf>) -> Result<Vec<PathBuf>> {
    roots
        .into_iter()
        .map(|root| {
            root.canonicalize()
                .with_context(|| format!("host root does not exist: {}", root.display()))
        })
        .collect()
}

fn write_config(path: &Path, config: &HostConfig) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(parent, fs::Permissions::from_mode(0o700))?;
        }
    }
    let bytes = serde_json::to_vec_pretty(config)?;
    let parent = path.parent().unwrap_or_else(|| Path::new("."));
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("host.json");
    let temporary = parent.join(format!(".{file_name}.tmp-{}", Uuid::new_v4()));
    let result = (|| -> std::io::Result<()> {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&temporary)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&temporary, fs::Permissions::from_mode(0o600))?;
        }
        file.write_all(&bytes)?;
        file.sync_all()?;
        replace_config_file(&temporary, path)?;
        #[cfg(unix)]
        fs::File::open(parent)?.sync_all()?;
        Ok(())
    })();
    if let Err(error) = result {
        let _ = fs::remove_file(&temporary);
        return Err(error).with_context(|| format!("failed to write {}", path.display()));
    }
    Ok(())
}

#[cfg(not(windows))]
fn replace_config_file(temporary: &Path, destination: &Path) -> std::io::Result<()> {
    fs::rename(temporary, destination)
}

#[cfg(windows)]
fn replace_config_file(temporary: &Path, destination: &Path) -> std::io::Result<()> {
    match fs::remove_file(destination) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    fs::rename(temporary, destination)
}

fn validate_server_url(server: &str) -> Result<String> {
    let server = server.trim().trim_end_matches('/');
    ensure!(!server.is_empty(), "remote server URL is empty");
    let parsed = Url::parse(server).with_context(|| "invalid remote server URL")?;
    ensure!(
        parsed.username().is_empty() && parsed.password().is_none(),
        "remote server URL must not contain userinfo"
    );
    ensure!(
        parsed.query().is_none() && parsed.fragment().is_none(),
        "remote server URL must not contain a query or fragment"
    );
    ensure!(
        parsed.path().is_empty() || parsed.path() == "/",
        "remote server URL must not contain a path"
    );
    let host = parsed.host().context("remote server URL has no host")?;
    match parsed.scheme() {
        "https" => {}
        "http"
            if matches!(host, Host::Domain("localhost"))
                || matches!(host, Host::Ipv4(address) if address.is_loopback())
                || matches!(host, Host::Ipv6(address) if address.is_loopback()) => {}
        "http" => bail!(
            "remote server must use HTTPS; plain HTTP is allowed only for loopback development servers"
        ),
        scheme => bail!("unsupported remote server URL scheme `{scheme}`; use HTTPS"),
    }
    Ok(server.to_string())
}

fn endpoint(server: &str, path: &str) -> String {
    format!("{}{}", server.trim_end_matches('/'), path)
}

